/// <summary>
/// The keys used to decide "new vs. duplicate" against what's already in the destination
/// database — deliberately independent of <see cref="ParsedProductRow.ImportKey"/> (see its doc
/// comment). Category → <c>Slug</c>. Product → case-insensitive (<c>CategorySlug</c>, <c>NameEn</c>).
/// Variant → <c>Sku</c>. Digital code → <c>CodeHash</c> (SHA-256 of the normalized code, already
/// computed by <see cref="HAMBOX.Modules.Catalog.Domain.Inventory.DigitalInventoryCode.ComputeHash"/>).
/// </summary>
public static class CatalogDedupeKeys
{
    public const string Category = "Slug";
    public const string Product = "CategorySlug+NameEn";
    public const string Variant = "Sku";
    public const string Code = "CodeHash";
}
